import { provideHttpClient } from '@angular/common/http';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { TestBed } from '@angular/core/testing';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { BranchesPage } from './branches.page';

const json = (body: unknown) => new Blob([JSON.stringify(body)], { type: 'application/json' });
const campuses = [
  { id: 'b1', name: 'Main campus', code: '0001', displayCode: '0001', kind: 'Main' },
  { id: 'b2', name: 'Karachi', code: '0002', displayCode: 'KHI0002', kind: 'Other' },
];
const settings = { prefixEnabled: true, prefix: 'KHI' };

async function render() {
  TestBed.configureTestingModule({ imports: [BranchesPage], providers: [provideHttpClient(), provideHttpClientTesting()] });
  const http = TestBed.inject(HttpTestingController);
  const fixture = TestBed.createComponent(BranchesPage);
  fixture.detectChanges();
  http.expectOne('/api/Branches').flush(json(campuses));
  http.expectOne('/api/Branches/settings').flush(json(settings));
  const element = fixture.nativeElement as HTMLElement;
  // The generated client reads every response as a Blob, which is read asynchronously.
  await vi.waitFor(() => {
    fixture.detectChanges();
    expect(element.querySelectorAll('.mm-branches__row').length).toBe(2);
  });
  return { fixture, http, element };
}

const input = (element: HTMLElement, name: string) => element.querySelector<HTMLInputElement>(`input[formcontrolname="${name}"]`)!;
const type = (element: HTMLElement, name: string, value: string, fixture: { detectChanges(): void }) => {
  input(element, name).value = value;
  input(element, name).dispatchEvent(new Event('input'));
  fixture.detectChanges();
};

describe('BranchesPage', () => {
  afterEach(() => TestBed.inject(HttpTestingController).verify());

  it('lists the campuses with their codes as the school shows them', async () => {
    const { element } = await render();

    const rows = [...element.querySelectorAll('.mm-branches__row')].map((row) => row.textContent ?? '');
    expect(rows[0]).toContain('Main campus');
    expect(rows[0]).toContain('0001');
    expect(rows[1]).toContain('Karachi');
    expect(rows[1]).toContain('KHI0002');
  });

  it('adds a campus by name only; its code is generated by the server', async () => {
    const { fixture, http, element } = await render();

    type(element, 'name', '  Lahore ', fixture);
    [...element.querySelectorAll('form')].find((form) => form.querySelector('input[formcontrolname="name"]'))!.querySelector<HTMLButtonElement>('button[type="submit"]')!.click();

    const request = http.expectOne({ method: 'POST', url: '/api/Branches' });
    expect(JSON.parse(request.request.body as string)).toEqual({ name: 'Lahore' });
    request.flush(json('0190f3a0-0000-7000-8000-000000000044'));
    await vi.waitFor(() => http.expectOne({ method: 'GET', url: '/api/Branches' }).flush(json(campuses)));
  });

  it('saves the prefix in upper case, and needs a prefix while it is on', async () => {
    const { fixture, http, element } = await render();

    type(element, 'prefix', '', fixture);
    expect(element.querySelector<HTMLButtonElement>('button[type="submit"]:not([disabled])')).toBeNull();

    type(element, 'prefix', 'khi', fixture);
    element.querySelector<HTMLButtonElement>('button[type="submit"]')!.click();

    const request = http.expectOne({ method: 'PUT', url: '/api/Branches/settings' });
    expect(JSON.parse(request.request.body as string)).toMatchObject({ prefixEnabled: true, prefix: 'KHI' });
    request.flush(null, { status: 204, statusText: 'No Content' });
    await vi.waitFor(() => http.expectOne({ method: 'GET', url: '/api/Branches/settings' }).flush(json(settings)));
    await vi.waitFor(() => http.expectOne({ method: 'GET', url: '/api/Branches' }).flush(json(campuses)));
  });
});
