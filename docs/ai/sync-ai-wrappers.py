#!/usr/bin/env python3
"""Generate the tool-specific wrapper files for the AI skills in docs/ai/.

The canonical, AI-agnostic text lives only in docs/ai/**/SKILL.md (plain Markdown with
name/description frontmatter). Every AI tool gets thin generated pointers so that all of
them see the same skills:

  Claude Code      .claude/skills/<name>/SKILL.md          (skills, loaded on demand by description)
  Cursor           .cursor/rules/<name>.mdc                (project rules; overview always applied)
  GitHub Copilot   .github/instructions/<name>.instructions.md  (applyTo: "**")
  Gemini CLI       GEMINI.md block with @imports           (imported into context at start)
  Codex / ChatGPT  AGENTS.md block with the skills index   (AGENTS.md is read at start)

There are two skill families, each with an overview SKILL.md, topic skills in subfolders and a
sources.json listing the official sources behind them:

  docs/ai/secure-compliance/   security and compliance rules  (tool names: secure-compliance, compliance-*)
  docs/ai/engineering/         engineering rules              (tool names: engineering-standards, engineering-*)

It also keeps two overviews in sync with each family's sources.json:

  Each skill       "Sources and update checks" block (version tracked, how it is checked)
  README.md        one skills table per family with the sources and versions each skill tracks

and fails --check if a skill that needs a source has none (every standard-* compliance skill and
every engineering topic skill), or a source names a skill that does not exist.

Usage (from the repo root):
  python3 docs/ai/sync-ai-wrappers.py          # write/refresh all wrappers
  python3 docs/ai/sync-ai-wrappers.py --check  # exit 1 if any wrapper is missing or stale

Standard library only. Run it after adding, renaming or re-describing a skill.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BEGIN = "<!-- BEGIN GENERATED: ai skills (docs/ai/sync-ai-wrappers.py) -->"
END = "<!-- END GENERATED: ai skills -->"
SRC_BEGIN = "<!-- BEGIN GENERATED: sources (docs/ai/sync-ai-wrappers.py) -->"
SRC_END = "<!-- END GENERATED: sources -->"
HEADER = "Generated by docs/ai/sync-ai-wrappers.py from the canonical skill. Do not edit; edit the canonical file and re-run the script."


FAMILIES = [
    {
        "key": "compliance",
        "dir": ROOT / "docs" / "ai" / "secure-compliance",
        "prefix": "compliance-",
        "suffix": " Part of the mandatory Education Portal compliance rules.",
        "needs_source": lambda name: name.startswith("standard-"),
        "missing_source": "standard skill has no source in sources.json (add one so updates are checked)",
        "readme_title": "Compliance skills and update checks",
        "readme_intro": "All compliance skills in the repository (generated from `docs/ai/secure-compliance/` and its `sources.json` "
                        "by `docs/ai/sync-ai-wrappers.py`, so this list is always current).",
        "kind": lambda s: "Overview" if s["overview"] else ("Standard" if s["name"].startswith("standard-") else "Topic"),
        "no_sources": "(rules only; see the standard skills)",
    },
    {
        "key": "engineering",
        "dir": ROOT / "docs" / "ai" / "engineering",
        "prefix": "engineering-",
        "suffix": " Part of the mandatory Education Portal engineering rules.",
        "needs_source": lambda name: True,
        "missing_source": "engineering skill has no source in sources.json (add the official guidance it follows so updates are checked)",
        "readme_title": "Engineering skills and update checks",
        "readme_intro": "All engineering skills in the repository (generated from `docs/ai/engineering/` and its `sources.json` "
                        "by `docs/ai/sync-ai-wrappers.py`, so this list is always current).",
        "kind": lambda s: "Overview" if s["overview"] else "Topic",
        "no_sources": "(index; see the topic skills)",
    },
]


def read_skill(path: Path, family: dict) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\nname: (.+)\ndescription: (.+)\n---\n", text)
    if not m:
        sys.exit(f"{path}: missing name/description frontmatter")
    rel = path.relative_to(ROOT).as_posix()
    is_overview = path.parent == family["dir"]
    return {"name": m.group(1).strip(), "desc": m.group(2).strip(), "rel": rel, "overview": is_overview,
            "family": family}


def skills(family: dict) -> list[dict]:
    base = family["dir"]
    items = [read_skill(base / "SKILL.md", family)]
    items += [read_skill(p, family) for p in sorted(base.glob("*/SKILL.md"))]
    return items


def tool_name(s: dict) -> str:
    return s["name"] if s["overview"] else f"{s['family']['prefix']}{s['name']}"


def yaml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def pointer_body(s: dict, up: str) -> str:
    ov = (s["family"]["dir"] / "SKILL.md").relative_to(ROOT).as_posix()
    overview = "" if s["overview"] else f", together with the overview in [{ov}]({up}{ov})"
    return (
        f"<!-- {HEADER} -->\n\n"
        f"**MUST FOLLOW.** Read and follow [{s['rel']}]({up}{s['rel']}) in full{overview}. "
        "If a request would break one of its rules, stop and name the rule ID.\n"
    )


def expected_files(items: list[dict]) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for s in items:
        n = tool_name(s)
        # Claude Code skill
        files[ROOT / ".claude" / "skills" / n / "SKILL.md"] = (
            f"---\nname: {n}\ndescription: {s['desc']}\n---\n\n" + pointer_body(s, "../../../")
        )
        # Cursor project rule
        always = "true" if s["overview"] else "false"
        files[ROOT / ".cursor" / "rules" / f"{n}.mdc"] = (
            f"---\ndescription: {s['desc']}\nglobs:\nalwaysApply: {always}\n---\n\n"
            + pointer_body(s, "../../")
            + f"\n@{s['rel']}\n"
        )
        # GitHub Copilot path-specific instructions
        files[ROOT / ".github" / "instructions" / f"{n}.instructions.md"] = (
            f"---\napplyTo: \"**\"\ndescription: {yaml_str(s['desc'])}\n---\n\n" + pointer_body(s, "../../")
        )
    return files


def agents_block(items: list[dict]) -> str:
    rows = ["| Skill | File | Use it when |", "|---|---|---|"]
    for s in items:
        when = s["desc"].replace(s["family"]["suffix"], "")
        rows.append(f"| `{s['name']}` | [{s['rel']}]({s['rel']}) | {when} |")
    return (
        f"{BEGIN}\n"
        "All AI skills (same list for every tool). Read both overviews (`secure-compliance` and `engineering-standards`) "
        "first, then every skill that matches the change:\n\n"
        + "\n".join(rows)
        + f"\n{END}"
    )


def gemini_block(items: list[dict]) -> str:
    imports = "\n".join(f"@./{s['rel']}" for s in items)
    return (
        f"{BEGIN}\n"
        "Gemini CLI imports every skill below into context at start, so all compliance and engineering rules are always loaded:\n\n"
        f"{imports}\n{END}"
    )


def replace_block(text: str, block: str, anchor: str | None, begin: str = BEGIN, end: str = END) -> str:
    if begin in text:
        return re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    if anchor is None:  # append at the end of the file
        return text.rstrip("\n") + "\n\n" + block + "\n"
    if anchor not in text:
        sys.exit(f"anchor not found: {anchor!r}")
    return text.replace(anchor, block + "\n\n" + anchor, 1)


def load_sources(family: dict, items: list[dict]) -> tuple[dict[str, list[dict]], list[str]]:
    """Map skill name -> sources that skill tracks; also return consistency errors."""
    sources = family["dir"] / "sources.json"
    data = json.loads(sources.read_text(encoding="utf-8"))
    names = {s["name"] for s in items}
    label = sources.relative_to(ROOT).as_posix()
    by_skill: dict[str, list[dict]] = {}
    errors = []
    for src in data["sources"]:
        for key in ("id", "name", "portal", "tracked_version", "skills", "last_reviewed"):
            if not src.get(key):
                errors.append(f"{label}: source {src.get('id', '?')!r} has no {key!r}")
        for skill in src.get("skills", []):
            if skill not in names:
                errors.append(f"{label}: source {src['id']!r} names unknown skill {skill!r}")
            by_skill.setdefault(skill, []).append(src)
    for s in items:
        if not s["overview"] and family["needs_source"](s["name"]) and s["name"] not in by_skill:
            errors.append(f"{s['rel']}: {family['missing_source']}")
    return by_skill, errors


def how_checked(src: dict) -> str:
    watch = src.get("watch") or {}
    if watch.get("type") == "github-path":
        where = f"{watch['repo']}/{watch['path']}".rstrip("/")
        return f"Automatic: new commits in `{where}`"
    return "Manual: listed for a portal check"


def sources_block(srcs: list[dict]) -> str:
    rows = ["| Source | Version tracked | How it is checked | Last reviewed |", "|---|---|---|---|"]
    for src in srcs:
        rows.append(f"| [{src['name']}]({src['portal']}) | {src['tracked_version']} | {how_checked(src)} | {src['last_reviewed']} |")
    return (
        f"{SRC_BEGIN}\n"
        "## Sources and update checks\n\n"
        "This skill is written against the versions below, recorded in [sources.json](../sources.json). "
        "`.github/workflows/compliance-sources-review.yml` checks every source on the 1st and 16th of each month and "
        "opens or updates a `compliance-review` issue. To apply a change: update this skill and any affected topic "
        "skills, then `tracked_version`, `last_seen_sha` and `last_reviewed` in sources.json, in one PR into "
        "`development`, and run `python3 docs/ai/sync-ai-wrappers.py`. The workflow never edits rules itself.\n\n"
        + "\n".join(rows)
        + f"\n{SRC_END}"
    )


def readme_markers(family: dict) -> tuple[str, str]:
    k = family["key"]
    return (f"<!-- BEGIN GENERATED: {k} skills (docs/ai/sync-ai-wrappers.py) -->",
            f"<!-- END GENERATED: {k} skills -->")


def readme_block(family: dict, items: list[dict], by_skill: dict[str, list[dict]]) -> str:
    begin, end = readme_markers(family)
    rows = ["| Skill | Kind | Sources and versions tracked |", "|---|---|---|"]
    for s in items:
        srcs = "; ".join(f"{x['tracked_version']}" for x in by_skill.get(s["name"], [])) or family["no_sources"]
        rows.append(f"| [{s['name']}]({s['rel']}) | {family['kind'](s)} | {srcs} |")
    return (
        f"{begin}\n"
        f"#### {family['readme_title']}\n\n"
        f"{family['readme_intro']} Every source is checked for updates on the "
        "1st and 16th of each month by `.github/workflows/compliance-sources-review.yml`, which opens a "
        "`compliance-review` issue.\n\n"
        + "\n".join(rows)
        + f"\n{end}"
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    readme = ROOT / "README.md"
    readme_text = readme.read_text(encoding="utf-8")
    items: list[dict] = []
    files: dict[Path, str] = {}
    errors: list[str] = []
    for family in FAMILIES:
        fam_items = skills(family)
        by_skill, fam_errors = load_sources(family, fam_items)
        errors += fam_errors
        items += fam_items
        # Sources block inside each canonical skill that tracks a source
        for s in fam_items:
            if s["name"] in by_skill:
                path = ROOT / s["rel"]
                files[path] = replace_block(path.read_text(encoding="utf-8"), sources_block(by_skill[s["name"]]),
                                            None, SRC_BEGIN, SRC_END)
        begin, end = readme_markers(family)
        readme_text = replace_block(readme_text, readme_block(family, fam_items, by_skill), "### Roadmap", begin, end)
    names_seen: dict[str, str] = {}
    for s in items:
        if s["name"] in names_seen:
            errors.append(f"{s['rel']}: skill name {s['name']!r} is also used by {names_seen[s['name']]}")
        names_seen[s["name"]] = s["rel"]
    if errors:
        print("\n".join(errors))
        return 1
    files.update(expected_files(items))
    files[readme] = readme_text

    agents = ROOT / "AGENTS.md"
    files[agents] = replace_block(agents.read_text(encoding="utf-8"), agents_block(items), "## 8. MVP plan")
    gemini = ROOT / "GEMINI.md"
    files[gemini] = replace_block(gemini.read_text(encoding="utf-8"), gemini_block(items), "Key rules, in short")

    # Generated wrappers that no longer have a canonical skill
    managed = [
        (ROOT / ".claude" / "skills", "*/SKILL.md", lambda p: p.parent.name),
        (ROOT / ".cursor" / "rules", "*.mdc", lambda p: p.stem),
        (ROOT / ".github" / "instructions", "*.instructions.md", lambda p: p.name.removesuffix(".instructions.md")),
    ]
    names = {tool_name(s) for s in items}
    stale = [
        p for base, pattern, key in managed if base.exists()
        for p in base.glob(pattern)
        if (key(p) in {"secure-compliance", "engineering-standards"}
            or key(p).startswith(tuple(f["prefix"] for f in FAMILIES))) and key(p) not in names
    ]

    problems = []
    for path, content in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            problems.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    for p in stale:
        problems.append(p)
        if not check:
            p.unlink()

    for p in problems:
        print(("stale: " if check else "updated: ") + p.relative_to(ROOT).as_posix())
    if check and problems:
        print("AI wrapper files are out of date. Run: python3 docs/ai/sync-ai-wrappers.py")
        return 1
    print(f"{len(items)} skills, {'OK' if not problems else str(len(problems)) + ' file(s) written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
