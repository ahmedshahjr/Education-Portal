#!/usr/bin/env python3
"""Keeps the "System flow" section of README.md in step with the code.

The section sits between two markers in README.md. This script rewrites what is between them from facts it reads in the
repository: the projects in the solution, the endpoint groups under Web/Endpoints and the feature areas of the Angular app.
Nothing in the generated block is typed by hand, so a change to those folders changes the README the next time this runs.

  python3 docs/ai/readme-flow.py            rewrite the block in README.md (the Claude Code hook and developers run this)
  python3 docs/ai/readme-flow.py --check    exit 1 when the block is out of date (the pre-commit hook runs this)

Standard library only, so it runs anywhere Python 3.9+ does. It never changes anything outside the markers.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
README = ROOT / "README.md"
SOLUTION_DIR = ROOT / "Education Portal Full Stack App"
SOLUTION = SOLUTION_DIR / "EducationPortal.slnx"
ENDPOINTS = SOLUTION_DIR / "src" / "Web" / "Endpoints"
FEATURES = SOLUTION_DIR / "src" / "Web" / "ClientApp" / "src" / "app" / "features"

BEGIN = "<!-- flow:begin (generated by docs/ai/readme-flow.py; edit the code, not this block) -->"
END = "<!-- flow:end -->"


def solution_projects() -> list[str]:
    """The project paths in the .slnx file, in order, as written there."""
    if not SOLUTION.exists():
        return []
    text = SOLUTION.read_text(encoding="utf-8-sig")
    return re.findall(r'<Project Path="([^"]+)"', text)


def endpoint_groups() -> list[str]:
    """The endpoint group classes: one file per group under Web/Endpoints (IEndpointGroup implementations)."""
    if not ENDPOINTS.exists():
        return []
    groups = []
    for path in sorted(ENDPOINTS.glob("*.cs")):
        if re.search(r"class\s+\w+\s*:\s*IEndpointGroup", path.read_text(encoding="utf-8-sig")):
            groups.append(path.stem)
    return groups


def feature_areas() -> list[str]:
    """The Angular feature folders (each one is a lazily loaded area of the app)."""
    if not FEATURES.exists():
        return []
    return sorted(p.name for p in FEATURES.iterdir() if p.is_dir())


def build_block() -> str:
    projects = solution_projects()
    tests = [p for p in projects if p.replace("\\", "/").startswith("tests/")]
    sources = [p for p in projects if not p.replace("\\", "/").startswith("tests/")]
    groups = endpoint_groups()
    features = feature_areas()

    lines = [
        BEGIN,
        "",
        "```mermaid",
        "flowchart LR",
        '    visitor(["Visitor opens the repository"]) --> has{"Has README.md?"}',
        '    has -- Yes --> render["GitHub parses the Markdown and the Mermaid diagrams"]',
        '    render --> page["Renders the project page"]',
        '    has -- No --> files["Displays the file list only"]',
        "",
        '    developer(["Developer clones the repository"]) --> prereq["Prerequisites: .NET 10, Node.js, Docker"]',
        '    prereq --> aspire["aspire run (src/AppHost)"]',
        f'    aspire --> api["API: {len(groups)} endpoint groups"]',
        f'    aspire --> web["Angular app: {len(features)} feature areas"]',
        '    aspire --> db[("PostgreSQL")]',
        "    web --> api",
        "    api --> db",
        "",
        f'    developer --> tests["dotnet test: {len(tests)} test projects"]',
        '    tests --> guards["Compliance and README guards (docs/ai)"]',
        '    guards --> pr["Pull request into development"]',
        "    pr --> ci{{CI runs the same guards}}",
        "```",
        "",
        f"The diagram is generated from the code: {len(sources)} source projects, {len(groups)} endpoint groups and "
        f"{len(features)} Angular feature areas. Each list below is read from the folder it names.",
        "",
        f"**Endpoint groups** (`Web/Endpoints`): {', '.join(f'`{g}`' for g in groups) if groups else 'none'}.",
        "",
        f"**Angular feature areas** (`src/Web/ClientApp/src/app/features`): {', '.join(f'`{f}`' for f in features) if features else 'none'}.",
        "",
        f"**Solution projects**: {', '.join(f'`{p}`' for p in projects) if projects else 'none'}.",
        "",
        END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    text = README.read_text(encoding="utf-8")
    newline = "\r\n" if "\r\n" in text else "\n"
    block = build_block().replace("\n", newline)

    pattern = re.compile(re.escape(BEGIN.split(" (")[0]) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        print("readme-flow: the markers are missing from README.md (add the section first)", file=sys.stderr)
        return 1

    updated = pattern.sub(lambda _: block, text, count=1)
    if updated == text:
        return 0

    if check_only:
        print("readme-flow: the System flow section in README.md is out of date.", file=sys.stderr)
        print("Run: python3 docs/ai/readme-flow.py   (then stage README.md)", file=sys.stderr)
        return 1

    README.write_text(updated, encoding="utf-8", newline="")
    print("readme-flow: updated the System flow section in README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
